/* Rebuild avatar-png.js from whatever painted art exists in spellbound-app/avatars/.
   Run from the app root: node voice/pipeline/avatar-manifest.js

   THIS SCRIPT USED TO GLOB `.png` ONLY, AND THAT MADE IT A LANDMINE. The full-size art was
   converted to WebP, so by the time the Spelling Champions pack was added there were zero
   `.png` files left in `avatars/` — running it wrote `{}` and silently un-painted all 211
   avatars in one line. It reverts every character to its vector fallback, and the five that
   have no vector fallback simply render blank, which is exactly the bug this was run to fix.

   It now accepts either extension, and it REFUSES to shrink the manifest: a generator whose
   failure mode is "quietly delete everything" is worse than no generator. Pass --force if a
   removal is genuinely intended. */
const fs = require('fs');

const ART = 'avatars';
const OUT = 'avatar-png.js';

const ids = fs.existsSync(ART)
  ? [...new Set(fs.readdirSync(ART)
      .filter(f => /\.(png|webp)$/i.test(f))
      .map(f => f.replace(/\.(png|webp)$/i, '')))].sort()
  : [];

// What is registered today, so a rebuild can be compared against it rather than trusted.
let prev = [];
try {
  const m = fs.readFileSync(OUT, 'utf8').match(/window\.SB_AVATAR_PNG\s*=\s*(\{[^;]*\})/);
  if (m) prev = Object.keys(JSON.parse(m[1]));
} catch (e) { /* first run */ }

const lost = prev.filter(id => !ids.includes(id));
if (lost.length && !process.argv.includes('--force')) {
  console.error(`REFUSING to write ${OUT}: ${lost.length} id(s) would lose their painted art`);
  console.error('  ' + lost.slice(0, 12).join(', ') + (lost.length > 12 ? ' …' : ''));
  console.error(`  ${ART}/ holds ${ids.length} art files against ${prev.length} registered.`);
  console.error('  Check the art directory before assuming this is right; pass --force to override.');
  process.exit(1);
}

const body = ids.length ? '{' + ids.map(i => JSON.stringify(i) + ':1').join(',') + '}' : '{}';
fs.writeFileSync(OUT,
`/* SB_AVATAR_PNG — which avatars have painted art in avatars/<id>.webp (or .png).
   Generated by voice/pipeline/avatar-manifest.js after an art batch; SB_AVATAR
   (avatars.js) renders the image instead of the SVG for every id listed here,
   and falls back to the vector art for anything missing — an id that is absent
   here AND has no vector fallback renders as nothing at all. Keep append-only in
   spirit: removing an id silently reverts that character to its SVG. */
window.SB_AVATAR_PNG = ${body};
`);
const added = ids.filter(id => !prev.includes(id));
console.log(`${OUT}: ${ids.length} painted avatars` + (added.length ? ` (+${added.length}: ${added.join(', ')})` : ''));
