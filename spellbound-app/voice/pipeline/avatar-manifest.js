/* Rebuild avatar-png.js from whatever PNGs exist in spellbound-app/avatars/.
   Run from the app root: node voice/pipeline/avatar-manifest.js */
const fs = require('fs');
const ids = fs.existsSync('avatars')
  ? fs.readdirSync('avatars').filter(f => f.endsWith('.png')).map(f => f.replace(/\.png$/, '')).sort()
  : [];
const body = ids.length ? '{' + ids.map(i => JSON.stringify(i) + ':1').join(',') + '}' : '{}';
fs.writeFileSync('avatar-png.js',
`/* SB_AVATAR_PNG — which avatars have painted PNG art in avatars/<id>.png.
   Generated by voice/pipeline/avatar-manifest.js after an art batch; SB_AVATAR
   (avatars.js) renders the image instead of the SVG for every id listed here,
   and falls back to the vector art for anything missing. Keep append-only in
   spirit: removing an id silently reverts that character to its SVG. */
window.SB_AVATAR_PNG = ${body};
`);
console.log('avatar-png.js:', ids.length, 'painted avatars');
