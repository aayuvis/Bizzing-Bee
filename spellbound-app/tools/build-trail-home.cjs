#!/usr/bin/env node
/* HOME'S ATLAS WITHOUT THE ATLAS (road to 4.5, P1.13 step 3 — first-load JS ≤ 400 KB gzip).

   Home's "You are here" card and its Continue strip read the child's place on the Word Atlas (SB_TRAIL_HERE,
   SB_TRAIL_NEXT — trail-home.js) — the road, the frontier, "Stop n of N", the region's name. That used to need all of
   trail-data.js (the curriculum: every stop's chapter, quiz and bands, ~75 KB gz) and trail.js (the Atlas itself,
   ~49 KB gz) on a returning speller's first screen. What those two functions read is only the ROAD: each region's id,
   title, world and stop list, each stop's id, title and laps, and the rule that puts a checkpoint after every N stops.
   This writes exactly that, cut from trail-data.js, into trail-home-data.js (SB_TRAIL_HOME, a boot script, ~3 KB gz);
   trail-road.js builds the same road from it as from the whole curriculum, and trail-home.js prefers the whole one
   whenever it has landed. Never typed: change trail-data.js (voice/pipeline/trail-build.js) and re-run this.

   tests/trail-home.cjs rebuilds and compares, and checks the road, the frontier and both readings are the same from
   the summary as from the curriculum for every region and many children (home-here and placement-step run the page).

     node tools/build-trail-home.cjs           write trail-home-data.js
     node tools/build-trail-home.cjs --check   exit 1 if trail-home-data.js is not what this would write          */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), zlib = require('zlib');
const APP = path.resolve(__dirname, '..');
const OUT = path.join(APP, 'trail-home-data.js');

function trail() { const w = {}; w.window = w; vm.runInNewContext(fs.readFileSync(path.join(APP, 'trail-data.js'), 'utf8'), w, { filename: 'trail-data.js' }); return w.SB_TRAIL; }

/* the road and nothing else: what trail-road.js nodes() and trail-home.js read */
function summary(T) {
  T = T || trail();
  const unit = (u) => { const o = { id: u.id, act: u.act, title: u.title }; if (u.lap != null) o.lap = u.lap; if (u.laps) o.laps = u.laps; return o; };
  const act = (a) => ({ id: a.id, title: a.title, world: a.world, units: a.units });
  return { rules: { checkpointEvery: T.rules.checkpointEvery },
    honey: { acts: T.honey.acts.map(act), units: T.honey.units.map(unit) },
    expedition: { expeds: T.expedition.expeds.map(act), units: T.expedition.units.map(unit) } };
}

function text(S) {
  return '/* trail-home-data.js — GENERATED by tools/build-trail-home.cjs from trail-data.js: the Word Atlas\'s ROAD only (each\n' +
    '   region\'s id, title, world and stops; each stop\'s id, title and laps; the checkpoint rule), which is all Home\'s\n' +
    '   "You are here" and Continue read (trail-home.js). Never edit it by hand — re-run the tool; tests/trail-home.cjs\n' +
    '   compares. Road to 4.5, P1.13 step 3: Home draws the Atlas card without trail-data.js or trail.js. */\n' +
    'window.SB_TRAIL_HOME=' + JSON.stringify(S) + ';\n';
}

if (require.main === module) {
  const t = text(summary());
  console.log(`trail-home-data.js ${(Buffer.byteLength(t) / 1024).toFixed(1)} KB raw · ${(zlib.gzipSync(t, { level: 6 }).length / 1024).toFixed(1)} KB gz`);
  if (process.argv.includes('--check')) {
    const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === t;
    console.log(ok ? 'trail-home-data.js is current' : 'trail-home-data.js is NOT what tools/build-trail-home.cjs writes — re-run it'); process.exit(ok ? 0 : 1);
  }
  fs.writeFileSync(OUT, t); console.log('wrote trail-home-data.js');
}
module.exports = { summary, text, trail, OUT };
