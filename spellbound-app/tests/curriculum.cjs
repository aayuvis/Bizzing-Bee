/* THE CURRICULUM IS DATA, AND IT IS THE SAME CURRICULUM (road to 4.5, P1.13 step 1 — first-load JS ≤ 400 KB). @check

   The boot word tier (words-data.js + words-extra.js + words-patch.js) left the first screen: it is boot-lazy's
   `words1` bundle. What Home's first render used to build from it is GENERATED by tools/build-curriculum.cjs, with
   app3's own code (tools/app3-closure.cjs), into curriculum-data.js (the 20 default stages, the word of the hour's
   seed — a boot script) and curriculum-ladder.js (the Journey ladder — in the words1 bundle). Here, in node:
     1. GENERATED: both files are exactly what the tool writes from the boot tier as the page loads it.
     2. THE SAME CURRICULUM, RECORD FOR RECORD: app3's RUNTIME functions — defaultStages(), journeySorted(),
        journeyStages() — read through the data return the SAME record objects, in
        the same order, as the algorithms (buildDefaultStages / buildJourneySorted) run over the boot tier; the
        ladder's Library levels and its in-level cluster order included.
     3. BEFORE THE TIER: with the bundle not in (wordsIn false) the stages and the ladder are the data's keys as thin
        records — the same words and counts — and nothing is memoised, so the real records take over when it lands.
     4. THE SCORES A RETURNING SPELLER'S LISTS WERE BUILT ON: trickSeal scores the tier with no homophone bonus even
        when sounds-data.js (SB_HOM) is already in — the ladder rebuilt from sealed records is the data's ladder; the
        Scripps winners sprinkle nothing into it (SB_SCRIPPS in hand changes no level).
     5. THE WORD OF THE HOUR'S SEED: per band, every k-th word of wohBandPool over the tier, in its order, carrying
        the word, its respelling and its meaning as far as the tile's trunc(d, 84) reads.
     6. WIRING: the three files are not in index.html, curriculum-data.js is; boot-lazy's words1 bundle runs them
        in order with the ladder, first on the idle queue, before words2 and the sentences, in every word group.
   The browser half (Home draws the same with and without the tier, nothing fetches it before a tap, a tap before it
   waits, the live page's lists equal the algorithm's) is tests/words-lazy.cjs.
   Run: NODE_PATH=/opt/node22/lib/node_modules node tests/curriculum.cjs
   PROVED by breaking (each put in, watched to fail, taken out): two stage-1 words swapped by hand in the data (3 fail:
   generated, the runtime stages, the thin stages); the homophone bonus on the tier — trickSeal without its blank index
   (3: the seal, the ladder, the Journey levels); the Scripps sprinkle put back (1); the thin ladder memoised before the
   tier (2); words-data.js back in index.html (1).                                                                */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const APP = path.resolve(__dirname, '..');
const B = require(path.join(APP, 'tools', 'build-curriculum.cjs'));
const { closure } = require(path.join(APP, 'tools', 'app3-closure.cjs'));
let fails = 0;
const ok = (b, m) => { console.log((b ? '  OK   ' : '  FAIL ') + m); if (!b) fails++; };
const read = (f) => fs.readFileSync(path.join(APP, f), 'utf8');

/* 1 — generated */
const C = B.build(), T = B.write(C);
ok(T.data === read('curriculum-data.js'), 'curriculum-data.js is exactly what tools/build-curriculum.cjs writes' + (T.data === read('curriculum-data.js') ? '' : ' — run node tools/build-curriculum.cjs'));
ok(T.ladder === read('curriculum-ladder.js'), 'curriculum-ladder.js is exactly what tools/build-curriculum.cjs writes' + (T.ladder === read('curriculum-ladder.js') ? '' : ' — run node tools/build-curriculum.cjs'));
ok(C.stages.length === 20 && C.stages.every((s, i) => s.length === (i ? 14 + i * 2 : 16)), 'twenty stages, 16 then 16 → 52 words (' + C.stages.map((s) => s.length).join(',') + ')');

/* 2 — the runtime, through the data, against the algorithm */
/* the build's context already holds the algorithms; the runtime functions are added by name (a const declared twice in
   one context would throw, so the runtime closure is evaluated in a FRESH context with the same data) */
function runtime(opts) {
  const win = { console }; win.window = win; win.document = {};
  const ctx = vm.createContext(win);
  for (const f of B.BOOT.concat(['kid-safe.js', 'wordband.js'])) vm.runInContext(read(f), ctx, { filename: f });
  if (opts.hom) vm.runInContext(read('sounds-data.js'), ctx, { filename: 'sounds-data.js' });
  if (opts.scripps) vm.runInContext(read('scripps-data.js'), ctx, { filename: 'scripps-data.js' });
  vm.runInContext(read('curriculum-data.js'), ctx, { filename: 'curriculum-data.js' });
  if (!opts.noLadder) vm.runInContext(read('curriculum-ladder.js'), ctx, { filename: 'curriculum-ladder.js' });
  win.SB_LAZY = { ready: () => !opts.before, state: () => (opts.before ? 'loading' : 'done'), need: () => {} };
  win.WORDS_LITERAL = vm.runInNewContext('(' + (() => { const s = read('app2.js'); const i = s.indexOf('const WORDS = ['); return s.slice(i + 'const WORDS = '.length, s.indexOf('\n];', i) + 2); })() + ')', {});
  vm.runInContext('const WORDS = window.WORDS_LITERAL;\n' +
    closure(['defaultStages', 'journeySorted', 'journeyStages', 'trickSeal', 'wordsIn', 'buildDefaultStages', 'buildJourneySorted', 'wohBandPool', 'wohPool', 'SB_UNSAFE_RE', 'CORE_STRIKE', 'CORE_CUT']) +
    '\nwindow.SB_UNSAFE_RE = SB_UNSAFE_RE; window.SB_CORE_STRIKE = CORE_STRIKE;', ctx, { filename: 'app3-runtime' });
  return { win, ctx, run: (x) => vm.runInContext(x, ctx) };
}
const keys = (a) => a.map((w) => w.w);
const same = (a, b) => a.length === b.length && a.every((x, i) => x === b[i]);

const R = runtime({});
R.run('trickSeal(SB_DATA.nsf)');   /* what the words1 listener does the moment the bundle lands */
const algoStages = R.run('buildDefaultStages(SB_DATA.nsf)'), liveStages = R.run('defaultStages()');
ok(liveStages.length === 20 && liveStages.every((s, i) => same(s.words, algoStages[i].words) && s.label === algoStages[i].label && s.n === algoStages[i].n),
  'defaultStages() through the data is buildDefaultStages(boot tier) — the same record OBJECTS, stage by stage, labels and all');
const algoLadder = R.run('buildJourneySorted(SB_DATA.nsf)'), liveLadder = R.run('journeySorted()');
ok(same(liveLadder, algoLadder), `journeySorted() through the data is buildJourneySorted(boot tier) — ${liveLadder.length} records, the same objects in the same order`);
const liveJst = R.run('journeyStages()');
R.run('_journeySorted = buildJourneySorted(SB_DATA.nsf); _journeyOrder = null; _journeyStages = null');
const algoJst = R.run('journeyStages()');
ok(liveJst.length === algoJst.length && liveJst.every((s, i) => same(s.words, algoJst[i].words) && s.label === algoJst[i].label && s.champ === algoJst[i].champ),
  `the Journey's ${liveJst.length} levels (20 Champ + ${liveJst.length - 20} Library) and their in-level cluster order are the same from the data as from the algorithm`);

/* 3 — before the tier */
const P = runtime({ before: true });
const preStages = P.run('defaultStages()'), preLadder = P.run('journeySorted()');
ok(preStages.length === 20 && preStages.every((s, i) => same(keys(s.words), C.stages[i])), 'before the tier: the stages are the data\'s words, thin, the same counts');
ok(same(keys(preLadder), C.ladder) && preLadder.every((w) => Object.keys(w).join() === 'w'), 'before the tier: the ladder is the data\'s words as thin records');
ok(P.run('_defStages === null && _journeySorted === null'), 'before the tier nothing is memoised — the real records take over when it lands');
const PL = runtime({ before: true, noLadder: true });
ok(PL.run('journeySorted().length === 0 && _journeySorted === null'), 'before the ladder file: an empty ladder, not memoised (it must never freeze empty)');

/* 4 — the scores: sealed with no homophone bonus, even with SB_HOM in hand; no Scripps sprinkle */
const H = runtime({ hom: true, scripps: true });
ok(H.run('Array.isArray(window.SB_HOM) && SB_HOM.length > 100 && Array.isArray(window.SB_SCRIPPS) && SB_SCRIPPS.length > 50'), 'the homophone groups and the Scripps winners are loaded for this check');
H.run('trickSeal(SB_DATA.nsf)');
const homHit = H.run("SB_DATA.nsf.filter(w => homIndex()[nkey(w.w)]).length");
ok(homHit > 50 && H.run('SB_DATA.nsf.every(w => !w.w || (w._tk && !(homIndex()[nkey(w.w)] && w._tk.cls === "hom")))'),
  `trickSeal scored all ${C.n} boot records with NO homophone bonus although ${homHit} of them are homophones and SB_HOM is in`);
ok(same(keys(H.run('buildJourneySorted(SB_DATA.nsf)')), C.ladder), 'the ladder rebuilt from the sealed records is the data\'s ladder');
const Hj = H.run('journeyStages()');
ok(Hj.length === algoJst.length && Hj.every((s, i) => same(keys(s.words), keys(algoJst[i].words))), 'with SB_SCRIPPS in hand the Journey\'s levels are unchanged — no winner is sprinkled in');

/* 5 — the word of the hour's seed */
const badSeed = [];
for (const b of [1, 2, 3, 4]) {
  const pool = R.run('wohBandPool(SB_DATA.nsf,' + b + ',window.SB_BAND,false)'), k = Math.max(1, Math.ceil(pool.length / B.SEED_MAX));
  const want = pool.filter((e, i) => i % k === 0), seed = C.woh[b];
  if (seed.length !== want.length) badSeed.push('band ' + b + ': ' + seed.length + ' vs ' + want.length);
  seed.forEach((r, i) => { const e = want[i]; if (!e || r[0] !== e.w || r[2] !== e.p || r[1] !== (e.d.length > 84 ? e.d.slice(0, 85) : e.d)) badSeed.push('band ' + b + ' #' + i + ' ' + r[0]); });
}
ok(!badSeed.length, `the word of the hour's seed is every k-th word of each band's pool, in order (${[1, 2, 3, 4].map((b) => b + ':' + C.woh[b].length).join(' ')})` + (badSeed.length ? ' — ' + badSeed.slice(0, 4).join(' | ') : ''));
const pre = runtime({ before: true });
ok([1, 2, 3, 4].every((b) => same(pre.run('wohPool(' + b + ').map(e => e.w)'), C.woh[b].map((r) => r[0]))), 'before the tier, wohPool(band) draws from the seed');

/* 6 — wiring */
const html = read('index.html'), lazy = read('boot-lazy.js');
const tags = [...html.matchAll(/<script[^>]*\ssrc="([^"?]+)/g)].map((m) => m[1]);
ok(!tags.some((t) => /^words-(data|extra|patch)\.js$/.test(t)) && tags.includes('curriculum-data.js') && !tags.includes('curriculum-ladder.js'),
  'index.html: no words-data / words-extra / words-patch script; curriculum-data.js is a boot script, the ladder is not');
ok(/words1:\s*\['words-data\.js', 'words-extra\.js', 'words-patch\.js', 'curriculum-ladder\.js'\]/.test(lazy), 'boot-lazy: the words1 bundle is the three files in their boot order, then the ladder');
ok(/var IDLE = \['words1',/.test(lazy) && /words2: \['words1'\]/.test(lazy) && /sents: \['words1'\]/.test(lazy), 'boot-lazy: words1 is first on the idle queue, and the second shard and the sentences wait for it');
const G = { addEventListener() {}, dispatchEvent() {} }; new Function('window', 'document', 'navigator', 'requestAnimationFrame', 'CustomEvent', lazy)(G, { readyState: 'loading', addEventListener() {}, querySelector() { return null; } }, {}, () => {}, function () {});
const groups = G.SB_LAZY.group, need1 = ['words', 'card', 'atlas', 'lists', 'themes', 'coach', 'arcade', 'gym', 'mockbee', 'daily', 'quizhubs', 'today', 'feed', 'placement', 'advanced', 'analogy', 'reader', 'curriculum', 'forge'];
const miss = need1.filter((g) => !(groups[g] || []).includes('words1'));
ok(!miss.length, 'every group a word is read through asks for words1 (' + need1.length + ' groups)' + (miss.length ? ' — missing in ' + miss.join(', ') : ''));

console.log(fails ? `\n${fails} FAILED` : '\nthe curriculum is data, and it is the same curriculum');
process.exit(fails ? 1 : 0);
